; 4004_edge.s -- 4004.axx の JCN / ISZ のページの回帰テスト。どの行も組めて、バイト列で比べる。
; 4004 は 2 バイトとも読んでから PC の下位 8 ビットを差し替えるので、ページは次の命令の
; 番地（$$+2）のページ。254・255 番地から始まる JCN / ISZ は次のページへ飛ぶ
        .org 0x0fd
        JCN 1,0x0e0             ; $$+2 = 0x0ff（ページ 0）
        .org 0x1fe
        JCN 2,0x210             ; $$+2 = 0x200（ページ 2）。以前は $$ で見てエラーにしていた
        .org 0x2ff
        ISZ 3,0x305             ; $$+2 = 0x301（ページ 3）
        .org 0x3fd
        JZ 0x3c0
