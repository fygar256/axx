; `**` とシフトのエラーのあとも 0 にして式の残りを読み進める
e 2**-1**2
e (2<<70000<<140)
e 1>>-1>>2
; 定義に失敗したラベル（二重定義・パターンファイルのシンボル）の行は残りも組まない
dup: e 1
dup: e 2
R0: e 3
; .EQU が複数セクションのラベルに触れたら、警告にセクション名を並べる
.section .text
t1: e 1
.section .data
d1: e 2
c1: .equ d1-t1
; 未定義を含む .EQU の値はセクション相対に直さず、未定義のまま後ろへ伝える
.section .data
u1: .equ nosuch+1
u2: .equ u1+2
e u2
; UTF-8 の多バイト文字は文字定数にならない
e 'é'
