; 6502_edge.s -- 6502.axx の範囲の境目の回帰テスト。どの行も組めて、バイト列で比べる。
; 負の番地は 16 ビットの 2 の補数（-1 は $FFFF）。自動選択は 0..$FF だけゼロページにする
        .org 0x0200
        LDA -1                  ; $AD $FF $FF（以前はゼロページ $A5 $FF になっていた）
        LDA >-1                 ; 同じ
        STA -0x8000,X           ; $9D $00 $80
        LDA 0xff                ; ゼロページ
        LDA 0x100               ; 絶対
        LDA #-0x80              ; 即値は -$80..$FF
        LDA #0xff
; ,Y と ,X の強制形（以前は構文エラーだった）
        STX <0x10,Y
        STY <0x10,X
        LDA >0x10,Y             ; 絶対,Y しか無いので > は同じ形
        STA >label,Y
label:  RTS
