        .org 0x00fc
        JZ 0x00e0               ; 2 バイト目は 0xfd（ページ 0）
        JNZ 0x00f0              ; 2 バイト目は 0xff（ページ 0）。以前は $$+2 で見てエラーにしていた
        .org 0x01ff
        JC 0x0210               ; 2 バイト目は 0x200（ページ 2）
        .org 0x02fe
        DJNZ R3,0x0280
        .org 0x03ff
        JB5 0x0400
        .org 0x07ff
        JT0 0x0010              ; 2 バイト目は 0x000（2K の中で回る）
        .org 0x08fe
        JF0 0x08c0              ; バンク 1 の中
        MOV A,#-128
        MOV R7,#0xff
        DB -1
        DB 0xff
